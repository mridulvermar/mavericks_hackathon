export function t(text, lang) {
  let selectedLang = lang;
  if (!selectedLang) {
    selectedLang = localStorage.getItem('sh_language');
  }
  if (!selectedLang) {
    try {
      const storedUser = JSON.parse(localStorage.getItem('sh_user') || '{}');
      selectedLang = storedUser.preferredLanguage;
    } catch {}
  }
  if (!selectedLang) {
    selectedLang = 'English';
  }

  if (selectedLang === 'English') return text;
  
  let cleanLang = selectedLang;
  if (cleanLang.includes('Tamil')) cleanLang = 'Tamil';
  else if (cleanLang.includes('Hindi')) cleanLang = 'Hindi';
  else if (cleanLang.includes('Marathi')) cleanLang = 'Marathi';
  else if (cleanLang.includes('Telugu')) cleanLang = 'Telugu';

  const translations = TRANSLATIONS[cleanLang];
  if (!translations) return text;
  
  return translations[text] || text;
}
